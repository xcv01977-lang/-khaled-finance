// Builds supabase/setup.sql: every migration in order, so a new project is set up by pasting one file.
// Run `npm run bundle-sql` after adding a migration; tests/setup-sql.test.ts fails if the file is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export function bundle(dir) {
  const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
  const parts = files.map((f) => `-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf8").trim()}\n`);
  return `-- Mizan: full database setup (all migrations in order). Paste into the Supabase SQL Editor and press Run, once.\n-- Generated by scripts/bundle-sql.mjs. Do not edit by hand.\n\n${parts.join("\n")}`;
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "supabase", "setup.sql"), bundle(join(root, "supabase", "migrations")));
  console.log("wrote supabase/setup.sql");
}
