// Builds supabase/setup.sql: every migration in order, so a new project is set up by pasting one file.
// Run `npm run bundle-sql` after adding a migration; tests/setup-sql.test.ts fails if the file is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** All migrations in order, or (with `after`) only those that come after that migration file, for a project already set up. */
export function bundle(dir, after = null) {
  const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort().filter((f) => !after || f > after);
  const parts = files.map((f) => `-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf8").trim()}\n`);
  const head = after
    ? `-- Mizan: upgrade for a project that already ran everything up to ${after}. Paste into the Supabase SQL Editor and press Run, once.`
    : "-- Mizan: full database setup (all migrations in order). Paste into the Supabase SQL Editor and press Run, once.";
  return `${head}\n-- Generated by scripts/bundle-sql.mjs. Do not edit by hand.\n\n${parts.join("\n")}`;
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = join(root, "supabase", "migrations");
  writeFileSync(join(root, "supabase", "setup.sql"), bundle(dir));
  writeFileSync(join(root, "supabase", "upgrade-from-phase1.sql"), bundle(dir, "0001_init.sql"));
  console.log("wrote supabase/setup.sql and supabase/upgrade-from-phase1.sql");
}
